from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
SOL = ROOT / "solutions"

def count(folder):
    return len([p for p in folder.glob("*.py") if p.name != "_template.py"])

def prettify(name):
    return name.replace("_", " ").title()

def build_progress():
    total = 0
    rows = []

    categories = sorted([f for f in SOL.iterdir() if f.is_dir()])

    for folder in categories:
        c = count(folder)
        total += c
        rows.append(f"| {prettify(folder.name)} | {c} |")

    table = "\n".join(rows)

    return f"""
## Progress

> Auto-generated by scripts/update_stats.py

- Total solved: **{total}**

| Category | Solved |
|--------|--------|
{table}
"""

def main():
    text = README.read_text()

    start = text.find("## Progress")
    end = text.find("---", start)

    if start == -1:
        print("No Progress section found.")
        return

    new_section = build_progress()

    updated = text[:start] + new_section + "\n---" + text[end+3:]
    README.write_text(updated)

    print("Stats updated successfully.")

if __name__ == "__main__":
    main()
