from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
SOL = ROOT / "solutions"

START = "<!-- STATS:START -->"
END = "<!-- STATS:END -->"


def count(folder: Path) -> int:
    if not folder.exists():
        return 0
    return len([p for p in folder.glob("*.py") if p.name != "_template.py"])


def prettify(name: str) -> str:
    return name.replace("_", " ").title()


def build_stats_block() -> str:
    # Collect categories with solved > 0
    total = 0
    rows = []

    if SOL.exists():
        for folder in sorted([d for d in SOL.iterdir() if d.is_dir()], key=lambda p: p.name):
            c = count(folder)
            total += c
            if c > 0:
                rows.append(f"| {prettify(folder.name)} | {c} |")

    # Only show rows > 0; if none, show empty state
    if rows:
        table = "\n".join(rows)
    else:
        table = "| (none yet) | 0 |"

    return (
        "> Auto-generated by scripts/update_stats.py\n\n"
        f"- Total solved: **{total}**\n\n"
        "| Category | Solved |\n"
        "|---|---|\n"
        f"{table}\n"
    )


def main():
    text = README.read_text(encoding="utf-8")

    if START not in text or END not in text:
        raise SystemExit(
            "README missing markers. Add these under ## Progress:\n"
            "<!-- STATS:START -->\n...\n<!-- STATS:END -->"
        )

    before, rest = text.split(START, 1)
    _, after = rest.split(END, 1)

    new_block = f"{START}\n{build_stats_block()}{END}"
    README.write_text(before + new_block + after, encoding="utf-8")

    print("Stats updated successfully.")


if __name__ == "__main__":
    main()
